#!/usr/bin/env bash
# DevPortal IA — Interactive Setup Wizard
# Generates devportal.config.yaml and .env from user choices.
# Usage: make setup
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
CONFIG_FILE="$PROJECT_ROOT/devportal.config.yaml"
ENV_FILE="$PROJECT_ROOT/.env"

# Terminal colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

info()  { echo -e "${CYAN}▸${NC} $*"; }
ok()    { echo -e "${GREEN}✓${NC} $*"; }
warn()  { echo -e "${YELLOW}!${NC} $*"; }
err()   { echo -e "${RED}✗${NC} $*" >&2; }
header(){ echo -e "\n${BOLD}── $* ──${NC}"; }

prompt_choice() {
  local var_name="$1"
  local prompt="$2"
  shift 2
  local options=("$@")
  local default="${options[0]}"

  echo -e "${CYAN}${prompt}${NC}"
  for i in "${!options[@]}"; do
    local mark=""
    [[ "${options[$i]}" == "$default" ]] && mark=" ${GREEN}(default)${NC}"
    echo -e "  $((i+1))) ${options[$i]}${mark}"
  done

  while true; do
    read -rp "  Choice [1-${#options[@]}, default=1]: " choice
    choice="${choice:-1}"
    if [[ "$choice" =~ ^[0-9]+$ ]] && (( choice >= 1 && choice <= ${#options[@]} )); then
      eval "$var_name=\"${options[$((choice-1))]}\""
      return
    fi
    err "Invalid choice"
  done
}

prompt_value() {
  local var_name="$1"
  local prompt="$2"
  local default="$3"
  read -rp "$(echo -e "${CYAN}${prompt}${NC} [${default}]: ")" value
  eval "$var_name=\"${value:-$default}\""
}

prompt_secret() {
  local var_name="$1"
  local prompt="$2"
  read -rsp "$(echo -e "${CYAN}${prompt}${NC}: ")" value
  echo
  eval "$var_name=\"$value\""
}

# ─── Start ─────────────────────────────────────────────────────
echo -e "\n${BOLD}DevPortal IA — Setup Wizard${NC}"
echo "This wizard generates devportal.config.yaml and .env"
echo ""

if [[ -f "$CONFIG_FILE" ]]; then
  warn "Config file already exists: $CONFIG_FILE"
  read -rp "  Overwrite? [y/N]: " ow
  [[ "$ow" != "y" && "$ow" != "Y" ]] && { info "Keeping existing config."; exit 0; }
fi

# ─── Adapters ──────────────────────────────────────────────────
header "Adapter Selection"

prompt_choice LLM_ADAPTER    "LLM Provider:" mock openai azure-openai anthropic ollama
prompt_choice GIT_ADAPTER    "Git Host:"     gitea github gitlab
prompt_choice NOTIFY_ADAPTER "Notifier:"     console slack teams email
prompt_choice ID_ADAPTER     "Identity:"     static-user entra-group oidc-group
prompt_choice SECRET_ADAPTER "Secrets:"      env kubernetes external-secrets

# ─── Cluster ───────────────────────────────────────────────────
header "Cluster Settings"

prompt_value CLUSTER_CONTEXT  "kubectl context name"  "kind-devportal"
prompt_value BASE_DOMAIN      "Base domain for Ingress" "dev.local"
prompt_value INGRESS_CLASS    "Ingress class"          "nginx"
prompt_value INGRESS_NS       "Ingress controller namespace" "ingress-nginx"
prompt_value NS_PREFIX        "Namespace prefix"       "env"

# ─── TTL ───────────────────────────────────────────────────────
header "TTL Settings"
prompt_value TTL_DEFAULT "Default TTL (days)" "3"
prompt_value TTL_MAX     "Max TTL (days)"     "14"

# ─── Collect secrets based on adapter choices ──────────────────
header "Credentials"
info "Only asking for credentials required by your selected adapters."
echo ""

ENV_CONTENT="# Generated by make setup — $(date -u +%Y-%m-%dT%H:%M:%SZ)\n# NEVER commit this file.\n"

case "$LLM_ADAPTER" in
  openai)
    prompt_secret OPENAI_KEY "OpenAI API key (sk-...)"
    ENV_CONTENT+="OPENAI_API_KEY=$OPENAI_KEY\n"
    ;;
  azure-openai)
    prompt_secret AZ_KEY "Azure OpenAI API key"
    prompt_value AZ_ENDPOINT "Azure OpenAI endpoint" ""
    prompt_value AZ_DEPLOY   "Azure OpenAI deployment name" ""
    ENV_CONTENT+="AZURE_OPENAI_API_KEY=$AZ_KEY\n"
    ENV_CONTENT+="AZURE_OPENAI_ENDPOINT=$AZ_ENDPOINT\n"
    ENV_CONTENT+="AZURE_OPENAI_DEPLOYMENT=$AZ_DEPLOY\n"
    ;;
  anthropic)
    prompt_secret ANT_KEY "Anthropic API key (sk-ant-...)"
    ENV_CONTENT+="ANTHROPIC_API_KEY=$ANT_KEY\n"
    ;;
  ollama)
    prompt_value OLLAMA_URL "Ollama URL" "http://localhost:11434"
    ENV_CONTENT+="OLLAMA_BASE_URL=$OLLAMA_URL\n"
    ;;
  mock)
    info "Mock LLM — no credentials needed."
    ;;
esac

case "$GIT_ADAPTER" in
  github|gitlab|gitea)
    prompt_secret GIT_TOKEN "Git access token"
    prompt_value GIT_REPO "Repository (owner/name)" "devportal/devportal-ia"
    ENV_CONTENT+="GIT_TOKEN=$GIT_TOKEN\n"
    ;;
esac

case "$NOTIFY_ADAPTER" in
  slack)
    prompt_secret SLACK_URL "Slack webhook URL"
    ENV_CONTENT+="SLACK_WEBHOOK_URL=$SLACK_URL\n"
    ;;
  teams)
    prompt_secret TEAMS_URL "Teams webhook URL"
    ENV_CONTENT+="TEAMS_WEBHOOK_URL=$TEAMS_URL\n"
    ;;
  email)
    prompt_value SMTP_HOST "SMTP host" "smtp.example.com"
    prompt_value SMTP_PORT "SMTP port" "587"
    prompt_secret SMTP_PASS "SMTP password"
    prompt_value SMTP_FROM "From address" "devportal@example.com"
    prompt_value SMTP_TO   "To address"   "team@example.com"
    ENV_CONTENT+="SMTP_HOST=$SMTP_HOST\nSMTP_PORT=$SMTP_PORT\nSMTP_PASS=$SMTP_PASS\n"
    ENV_CONTENT+="SMTP_FROM=$SMTP_FROM\nSMTP_TO=$SMTP_TO\n"
    ;;
  console)
    info "Console notifier — no credentials needed."
    ;;
esac

# Determine GIT_REPO for config (may have been set above or use default)
GIT_REPO="${GIT_REPO:-devportal/devportal-ia}"

# Determine LLM model
case "$LLM_ADAPTER" in
  openai)       LLM_MODEL="gpt-4o" ;;
  azure-openai) LLM_MODEL="${AZ_DEPLOY:-gpt-4o}" ;;
  anthropic)    LLM_MODEL="claude-sonnet-4-20250514" ;;
  ollama)       LLM_MODEL="llama3" ;;
  mock)         LLM_MODEL="mock" ;;
esac

# Determine git URL
case "$GIT_ADAPTER" in
  github) GIT_URL="https://github.com" ;;
  gitlab) GIT_URL="https://gitlab.com" ;;
  gitea)  GIT_URL="http://localhost:3000" ;;
esac

# ─── Write config ─────────────────────────────────────────────
cat > "$CONFIG_FILE" <<YAML
# Generated by make setup — $(date -u +%Y-%m-%dT%H:%M:%SZ)

adapters:
  llm: ${LLM_ADAPTER}
  git: ${GIT_ADAPTER}
  notifier: ${NOTIFY_ADAPTER}
  identity: ${ID_ADAPTER}
  secrets: ${SECRET_ADAPTER}

cluster:
  context: ${CLUSTER_CONTEXT}
  baseDomain: ${BASE_DOMAIN}
  ingressClass: ${INGRESS_CLASS}
  ingressNamespace: ${INGRESS_NS}

namespaces:
  prefix: ${NS_PREFIX}
  allowedRegistries:
    - docker.io
    - ghcr.io
    - registry.k8s.io

ttl:
  defaultDays: ${TTL_DEFAULT}
  maxDays: ${TTL_MAX}

sizes:
  small:
    cpu: "500m"
    memory: "512Mi"
    pods: 5
  medium:
    cpu: "2"
    memory: "2Gi"
    pods: 15
  large:
    cpu: "8"
    memory: "8Gi"
    pods: 30

approval:
  requireAboveSize: medium
  requireAboveTtlDays: 7

llm:
  model: ${LLM_MODEL}
  temperature: 0
  maxTokens: 2048

git:
  repo: ${GIT_REPO}
  baseBranch: main
  url: ${GIT_URL}
YAML

ok "Config written to $CONFIG_FILE"

# ─── Write .env ────────────────────────────────────────────────
echo -e "$ENV_CONTENT" > "$ENV_FILE"
ok "Secrets written to $ENV_FILE"

echo ""
ok "Setup complete. Run 'make doctor' to verify connectivity."
